
package dev.eventflow.orders.api.order;

import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.Test;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
@AutoConfigureMockMvc
@Testcontainers
class OrderApiIntegrationTest {

    @Container
    @ServiceConnection
    @SuppressWarnings("unused")
    static PostgreSQLContainer postgres =
            new PostgreSQLContainer("postgres:17");

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Test
    void shouldCreateAndRetrievePersistedOrder() throws Exception {
        UUID customerId = UUID.randomUUID();
        UUID productId = UUID.randomUUID();

        String request = """
                {
                  "customerId": "%s",
                  "items": [
                    {
                      "productId": "%s",
                      "quantity": 2,
                      "unitPrice": 49.90
                    }
                  ]
                }
                """.formatted(customerId, productId);

        // Create an order through the real HTTP layer.
        MvcResult result = mockMvc.perform(
                        post("/api/v1/orders")
                                .contentType(MediaType.APPLICATION_JSON)
                                .content(request)
                )
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.status").value("PENDING"))
                .andExpect(jsonPath("$.total").value(99.80))
                .andReturn();

        // Extract the ID generated by the domain.
        String responseBody =
                result.getResponse().getContentAsString();

        String orderId = JsonPath.read(responseBody, "$.id");

        assertEquals(
                "/api/v1/orders/" + orderId,
                result.getResponse().getHeader("Location")
        );

        // Retrieve the order in a separate HTTP request.
        mockMvc.perform(get("/api/v1/orders/{id}", orderId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(orderId))
                .andExpect(jsonPath("$.customerId")
                        .value(customerId.toString()))
                .andExpect(jsonPath("$.status").value("PENDING"))
                .andExpect(jsonPath("$.items.length()").value(1))
                .andExpect(jsonPath("$.items[0].productId")
                        .value(productId.toString()))
                .andExpect(jsonPath("$.items[0].quantity")
                        .value(2))
                .andExpect(jsonPath("$.total").value(99.80));

        // Verify that the order exists in PostgreSQL.
        Long count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM orders WHERE id = ?",
                Long.class,
                UUID.fromString(orderId)
        );

        assertEquals(1L, count);
    }

    @Test
    void shouldNotPersistInvalidOrder() throws Exception {
        Long countBefore = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM orders",
                Long.class
        );

        String request = """
            {
              "customerId": "%s",
              "items": [
                {
                  "productId": "%s",
                  "quantity": -5,
                  "unitPrice": 49.90
                }
              ]
            }
            """.formatted(
                UUID.randomUUID(),
                UUID.randomUUID()
        );

        mockMvc.perform(post("/api/v1/orders")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(request))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.title")
                        .value("Validation failed"))
                .andExpect(jsonPath("$.errors").isArray());

        Long countAfter = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM orders",
                Long.class
        );

        assertEquals(countBefore, countAfter);
    }

    @Test
    void shouldRejectMalformedJson() throws Exception {
        String invalidJson = """
            {
              "customerId": "invalid",
              "items": [
            }
            """;

        mockMvc.perform(post("/api/v1/orders")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(invalidJson))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldExposeOpenApiDocumentation() throws Exception {
        mockMvc.perform(get("/v3/api-docs"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.info.title")
                        .value("EventFlow - Order Service API"))
                .andExpect(jsonPath("$.info.version")
                        .value("0.2.0"))
                .andExpect(jsonPath(
                        "$.paths['/api/v1/orders'].post"
                ).exists())
                .andExpect(jsonPath(
                        "$.paths['/api/v1/orders/{id}'].get"
                ).exists());
    }
}
